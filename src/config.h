/*
 * config.h —— 掉电保存的整车参数（存在 ESP32 的 NVS 里，重新烧录也不会丢）
 *
 * 为什么要有这个：
 *   把车拼起来以后，"哪个轮子转向反了"几乎是一定会发生的事。
 *   如果每改一次方向都要重新编译 + 烧录（这块 CP2102 板子烧录还挺折腾），
 *   标定四个轮子能耗掉一晚上。
 *   所以把【方向 / 死区 / 限速】这些参数存进 NVS：
 *   在串口里按一个键就改好并永久保存，不用再烧录。
 *
 * 快捷键（详见 main.cpp 顶部）：
 *   q w e r → 翻转 左前 / 右前 / 左后 / 右后 的转向并保存
 *   m       → 循环切换最小占空比（电机转不动时调它）
 *   d       → 恢复出厂默认
 *   v       → 打印当前配置
 */

#pragma once

#include <Arduino.h>

#define WHEEL_COUNT 4

struct Settings {
  // 每个轮子的方向翻转：false = 正转（PWM 为正时该轮按"推车前进"方向转）
  bool    invert[WHEEL_COUNT];

  // 死区补偿：只要想动，至少给这么多占空比，否则电机哼一下不转
  uint8_t minDuty;

  // 输出上限：新手第一次试车建议先调到 120 左右，别一上来就满速
  uint8_t maxDuty;

  // 加速斜坡：每 5ms 变化多少（0 = 关闭，直接跳到目标值）
  // 有了它电机不会"啪"一下满功率启动，齿轮箱和电池都舒服些
  uint8_t rampStep;

  // ---------------- 操控手感（阶段 4）----------------

  // 摇杆曲线：0 = 线性；越大，中位附近越细腻、末端越激进（0~80）
  uint8_t expo;

  // 偏航修正：-30~+30（%）。前进时左右两侧差速补偿，修掉跑偏
  // 正数 = 右侧减速 → 车往右修
  int8_t yawTrim;

  // 原地转向力度：40~100（%）。麦轮原地转非常快，降一点更好控
  uint8_t rotScale;

  // 极性纠正：接线/机械差异导致"拐弯反了"或"横移反了"时，按一下键就行
  bool rotInv;     // true = 右摇杆右打 → 顺时针（默认，符合直觉）
  bool strafeInv;  // true = 左摇杆右打 → 向车右侧平移
};

void configBegin();     // setup() 里调用一次，从 NVS 读出参数
Settings &cfg();        // 取参数（可读可改）
void configSave();      // 改完必须调用，否则重启就丢
void configReset();     // 恢复默认并保存
void configPrint();     // 打印到 Serial
